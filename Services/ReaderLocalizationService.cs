    public static void ApplyLanguage(string? langCode)
    {
        string code = NormalizeLanguageCode(langCode);
        CurrentLanguageCode = code;

        var dict = Dictionaries[code];
        var fallback = Dictionaries["uk"];

        var appResources = Application.Current?.Resources;
        if (appResources != null)
        {
            foreach (var kv in fallback)
            {
                appResources[kv.Key] = dict.TryGetValue(kv.Key, out var translated) ? translated : kv.Value;
            }
        }

        LanguageChanged?.Invoke(code);
    }

    public static string NormalizeLanguageCode(string? langCode)
    {
        if (string.IsNullOrWhiteSpace(langCode))
            return "uk";

        string trimmed = langCode.Trim().ToLowerInvariant();
        if (trimmed is "ua" or "uk-ua")
            return "uk";
        if (trimmed.StartsWith("en"))
            return "en";
        if (trimmed.StartsWith("pl"))
            return "pl";
        if (trimmed.StartsWith("de"))
            return "de";
        if (trimmed.StartsWith("es"))
            return "es";
        if (trimmed.StartsWith("fr"))
            return "fr";
        if (trimmed.StartsWith("it"))
            return "it";
        if (trimmed.StartsWith("pt"))
            return "pt";
        if (trimmed.StartsWith("ja"))
            return "ja";
        if (trimmed.StartsWith("zh"))
            return "zh";

        return Dictionaries.ContainsKey(trimmed) ? trimmed : "uk";
    }

    public static string GetString(string key)
    {
        if (Dictionaries.TryGetValue(CurrentLanguageCode, out var dict) && dict.TryGetValue(key, out var val))
            return val;
        if (Dictionaries["uk"].TryGetValue(key, out var fb))
            return fb;
        return key;
    }
